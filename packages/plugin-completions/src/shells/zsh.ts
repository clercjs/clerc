/* eslint-disable no-template-curly-in-string -- Generated shell scripts use literal ${...} parameter expansion */
import { ShellCompDirective } from "../directives";
import type { StaticCompletionSpec } from "../spec";
import { emitPosixCore, emitPosixHelpers } from "./posix";

export function renderZshScript(spec: StaticCompletionSpec): string {
  const { name, bin, fn, hasDynamic } = spec;
  const entryFn = `_${fn}`;

  const lines: string[] = [
    `#compdef ${name}`,
    `compdef ${entryFn} ${name}`,
    "",
    `# zsh completion for ${name} -*- shell-script -*-`,
    "",
    ...emitPosixHelpers(spec, true),
    `${entryFn}() {`,
    "    setopt local_options NO_KSH_ARRAYS BASH_REMATCH",
    `    local shellCompDirectiveError=${ShellCompDirective.Error}`,
    `    local shellCompDirectiveNoSpace=${ShellCompDirective.NoSpace}`,
    `    local shellCompDirectiveNoFileComp=${ShellCompDirective.NoFileComp}`,
    `    local shellCompDirectiveFilterFileExt=${ShellCompDirective.FilterFileExt}`,
    `    local shellCompDirectiveFilterDirs=${ShellCompDirective.FilterDirs}`,
    `    local shellCompDirectiveKeepOrder=${ShellCompDirective.KeepOrder}`,
    "",
    "    local lastParam lastChar flagPrefix directive comp noSpace keepOrder",
    "    local -a completions",
    "",
    '    words=( "${=words[1,CURRENT]}" )',
    "    lastParam=${words[-1]}",
    "    lastChar=${lastParam[-1]}",
    "",
    `    if [[ "\${lastParam}" =~ '-.*=' ]]; then`,
    '        flagPrefix="-P ${BASH_REMATCH}"',
    "    fi",
    "",
    '    local -a args_to_quote=("${(@)words[2,-1]}")',
    '    if [[ "${lastChar}" == "" && "${args_to_quote[-1]}" != "" ]]; then',
    '        args_to_quote+=("")',
    "    fi",
    "",
    "    local -a prior=()",
    '    local cur=""',
    "    if (( ${#args_to_quote} > 1 )); then",
    '        prior=("${(@)args_to_quote[1,-2]}")',
    "    fi",
    "    if (( ${#args_to_quote} >= 1 )); then",
    '        cur="${args_to_quote[-1]}"',
    "    fi",
    "",
    ...emitPosixCore(spec, "zsh"),
  ];

  if (hasDynamic) {
    lines.push(
      "    if (( _use_dynamic == 1 )); then",
      '        local -a quoted_args=("${(@q)args_to_quote}")',
      `        local requestComp="${bin} complete -- \${quoted_args[*]}"`,
      "        local out",
      "        out=$(eval ${requestComp} 2>/dev/null)",
      "        local -a _dyn_lines",
      '        _dyn_lines=("${(@f)out}")',
      '        local lastLine="${_dyn_lines[-1]}"',
      '        if [[ "${lastLine[1]}" == ":" ]]; then',
      '            directive="${lastLine[2,-1]}"',
      "            if (( ${#_dyn_lines} > 1 )); then",
      '                _result_items=("${(@)_dyn_lines[1,-2]}")',
      "            else",
      "                _result_items=()",
      "            fi",
      "        else",
      "            directive=0",
      '            _result_items=("${(@)_dyn_lines}")',
      "        fi",
      "    fi",
      "",
    );
  }

  lines.push(
    "    if (( (directive & shellCompDirectiveError) != 0 )); then",
    "        return",
    "    fi",
    "",
    `    local _tab=$'\\t'`,
    '    for comp in "${_result_items[@]}"; do',
    '        if [[ -n "$comp" ]]; then',
    "            comp=${comp//:/\\\\:}",
    "            comp=${comp//$_tab/:}",
    '            completions+=("$comp")',
    "        fi",
    "    done",
    "",
    "    if (( (directive & shellCompDirectiveNoSpace) != 0 )); then",
    `        noSpace="-S ''"`,
    "    fi",
    "    if (( (directive & shellCompDirectiveKeepOrder) != 0 )); then",
    '        keepOrder="-V"',
    "    fi",
    "",
    "    if (( (directive & shellCompDirectiveFilterFileExt) != 0 )); then",
    "        local filteringCmd='_files'",
    "        local filter",
    "        for filter in ${completions[@]}; do",
    `            if [[ "\${filter[1]}" != '*' ]]; then`,
    `                filter="\\*.$filter"`,
    "            fi",
    '            filteringCmd+=" -g $filter"',
    "        done",
    '        filteringCmd+=" ${flagPrefix}"',
    `        _arguments '*:filename:'"$filteringCmd"`,
    "    elif (( (directive & shellCompDirectiveFilterDirs) != 0 )); then",
    '        local subdir="${completions[1]}"',
    '        if [[ -n "$subdir" ]]; then',
    '            pushd "${subdir}" >/dev/null 2>&1',
    "        fi",
    "        local result",
    `        _arguments '*:dirname:_files -/'" \${flagPrefix}"`,
    "        result=$?",
    '        if [[ -n "$subdir" ]]; then',
    "            popd >/dev/null 2>&1",
    "        fi",
    "        return $result",
    "    else",
    '        if eval _describe $keepOrder "completions" completions -Q ${flagPrefix} ${noSpace}; then',
    "            return 0",
    "        elif (( (directive & shellCompDirectiveNoFileComp) != 0 )); then",
    "            return 0",
    "        else",
    `            _arguments '*:filename:_files'" \${flagPrefix}"`,
    "        fi",
    "    fi",
    "}",
    "",
    `if [[ "\${funcstack[1]}" == "${entryFn}" ]]; then`,
    `    ${entryFn}`,
    "fi",
  );

  return lines.join("\n");
}
