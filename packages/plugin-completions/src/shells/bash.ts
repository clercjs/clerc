/* eslint-disable no-template-curly-in-string -- Generated shell scripts use literal ${...} parameter expansion */
import { ShellCompDirective } from "../directives";
import type { StaticCompletionSpec } from "../spec";
import { emitPosixCore, emitPosixHelpers } from "./posix";

export function renderBashScript(spec: StaticCompletionSpec): string {
  const { name, bin, fn, hasDynamic } = spec;
  const p = `__${fn}`;

  const lines: string[] = [
    `# bash completion for ${name}`,
    "",
    ...emitPosixHelpers(spec, false),
    `${p}_complete() {`,
    `    local shellCompDirectiveError=${ShellCompDirective.Error}`,
    `    local shellCompDirectiveNoSpace=${ShellCompDirective.NoSpace}`,
    `    local shellCompDirectiveNoFileComp=${ShellCompDirective.NoFileComp}`,
    `    local shellCompDirectiveFilterFileExt=${ShellCompDirective.FilterFileExt}`,
    `    local shellCompDirectiveFilterDirs=${ShellCompDirective.FilterDirs}`,
    `    local shellCompDirectiveKeepOrder=${ShellCompDirective.KeepOrder}`,
    "",
    "    local cur prev words cword directive",
    "    if declare -F _get_comp_words_by_ref >/dev/null 2>&1; then",
    '        _get_comp_words_by_ref -n "=:" cur prev words cword',
    "    else",
    '        words=("${COMP_WORDS[@]}")',
    "        cword=${COMP_CWORD}",
    '        cur="${words[cword]}"',
    "    fi",
    "",
    "    local -a req_args=() prior=()",
    "    local i",
    "    for (( i=1; i<=cword; i++ )); do",
    '        req_args+=("${words[i]}")',
    "        if (( i < cword )); then",
    '            prior+=("${words[i]}")',
    "        fi",
    "    done",
    "",
    ...emitPosixCore(spec, "bash"),
  ];

  if (hasDynamic) {
    lines.push(
      "    if (( _use_dynamic == 1 )); then",
      "        local out",
      `        out=$(${bin} complete -- "\${req_args[@]}" 2>/dev/null)`,
      "        directive=0",
      '        if [[ "$out" == *:* ]]; then',
      `            local _last_line="\${out##*$'\\n'}"`,
      '            if [[ "$_last_line" == :* ]]; then',
      '                directive="${_last_line#:}"',
      `                if [[ "$out" == *$'\\n'* ]]; then`,
      `                    out="\${out%$'\\n'*}"`,
      "                else",
      '                    out=""',
      "                fi",
      "            fi",
      "        fi",
      `        local _tab=$'\\t' _line _val`,
      "        _result_items=()",
      "        while IFS= read -r _line; do",
      '            [[ -z "$_line" ]] && continue',
      '            _val="${_line%%$_tab*}"',
      '            _result_items+=("$_val")',
      '        done <<< "$out"',
      "    fi",
      "",
    );
  }

  lines.push(
    "    if (( (directive & shellCompDirectiveError) != 0 )); then",
    "        return",
    "    fi",
    "    if (( (directive & shellCompDirectiveNoSpace) != 0 )); then",
    "        compopt -o nospace 2>/dev/null",
    "    fi",
    "    if (( (directive & shellCompDirectiveKeepOrder) != 0 )); then",
    "        compopt -o nosort 2>/dev/null",
    "    fi",
    "    if (( (directive & shellCompDirectiveNoFileComp) != 0 )); then",
    "        compopt +o default 2>/dev/null",
    "    fi",
    "",
    '    local flagPrefix="" matchCur="$cur"',
    '    if [[ "$cur" == -*=* ]]; then',
    '        flagPrefix="${cur%%=*}="',
    '        matchCur="${cur#*=}"',
    "    fi",
    "",
    "    if (( (directive & shellCompDirectiveFilterFileExt) != 0 )); then",
    '        local filter="" ext',
    '        for ext in "${_result_items[@]}"; do',
    '            filter="${filter:+$filter|}${ext}"',
    "        done",
    "        local _had_extglob=0",
    "        shopt -q extglob && _had_extglob=1",
    "        shopt -s extglob",
    "        compopt -o filenames 2>/dev/null",
    "        local -a _files=() _dirs=()",
    `        local _p _seen_paths=$'\\n'`,
    "        while IFS= read -r _p; do",
    '            [[ -z "$_p" ]] && continue',
    `            _seen_paths+="$_p"$'\\n'`,
    '            _files+=("${flagPrefix}${_p}")',
    '        done < <(compgen -f -X "!*.@($filter)" -- "$matchCur")',
    "        while IFS= read -r _p; do",
    '            [[ -z "$_p" ]] && continue',
    `            [[ "$_seen_paths" == *$'\\n'"$_p"$'\\n'* ]] && continue`,
    '            _dirs+=("${flagPrefix}${_p}")',
    '        done < <(compgen -d -- "$matchCur")',
    "        (( _had_extglob == 0 )) && shopt -u extglob",
    '        COMPREPLY=("${_dirs[@]}" "${_files[@]}")',
    "        return",
    "    fi",
    "",
    "    if (( (directive & shellCompDirectiveFilterDirs) != 0 )); then",
    "        compopt -o dirnames 2>/dev/null",
    "        local _p",
    "        COMPREPLY=()",
    "        while IFS= read -r _p; do",
    '            [[ -z "$_p" ]] && continue',
    '            COMPREPLY+=("${flagPrefix}${_p}")',
    '        done < <(compgen -d -- "$matchCur")',
    "        return",
    "    fi",
    "",
    "    local value",
    "    COMPREPLY=()",
    '    for value in "${_result_items[@]}"; do',
    '        if [[ "$value" == "$matchCur"* ]]; then',
    '            COMPREPLY+=("${flagPrefix}${value}")',
    "        fi",
    "    done",
    "}",
    "",
    `complete -o default -F ${p}_complete ${name}`,
  );

  return lines.join("\n");
}
